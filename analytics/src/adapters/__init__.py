# 来源适配器包：把外部真实/公开数据集的原始列，映射为治理链路的规范来源 CSV。
#
# 设计原则（与 docs/stage2/contracts.md 一致）：
#   1. 适配器只做三件事——列映射、单位换算、时区归一；不做聚合、不做发布、不写业务库。
#   2. 隐私列在本地受控区直接不写出（不是"先上传共享 raw 再脱敏"）。
#   3. 每个来源一个模块，输出同一种规范 CSV，后续复用 run_governance 的准入→质量→发布链。
#   4. 每行拒绝都有唯一主原因，诊断细节放 diagnostic_tags，保证"输入 = 通过 + 拒绝"可对账。
#
# 已实现：course_sessions（课程提供的真实充电会话数据，2014-2015）。
# 预留：acn（Caltech ACN，契约已预留 acn 命名空间；未启用、未下载数据）。
